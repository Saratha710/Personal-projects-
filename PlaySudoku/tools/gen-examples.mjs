// Finds a real board position for every trick so lesson pictures are always correct.
import fs from 'node:fs';
import * as E from '../www/js/engine.js';
const bank = JSON.parse(fs.readFileSync('data/bank.json', 'utf8'));
const all = [...bank.hard, ...bank.expert, ...bank.extreme, ...bank.medium];
const found = {};
const score = (t, st, filled) => (st.place ? Math.abs(filled - 50) : st.elim.length * 3 + Math.abs(filled - 38) / 4);
for (const str of all) {
  const g = E.parse(str);
  for (;;) {
    const fresh = E.makeState(g), filled = g.filter(Boolean).length;
    for (const t of E.TECHNIQUES) for (const st of t.find(fresh)) {
      if (t.id === 'hiddenSingle' && st.hl.sources.length < 2) continue;
      if (t.id === 'nakedSingle') {
        const c = st.place.cell, cnt = cs => cs.filter(x => !g[x]).length;
        if (cnt(E.UNITS[E.rowOf(c)].cells) < 2 || cnt(E.UNITS[9 + E.colOf(c)].cells) < 2 || cnt(E.UNITS[18 + E.boxOf(c)].cells) < 2) continue;
        if (st.lines.length < 5) continue;
      }
      const q = score(t, st, filled);
      if (!found[t.id] || q < found[t.id].q) found[t.id] = { q, id: t.id, grid: E.stringify(g), step: st };
    }
    const single = E.TECHNIQUES.slice(0, 3).map(t => t.find(fresh).next().value).find(Boolean);
    if (!single) break;
    g[single.place.cell] = single.place.val;
    if (g.every(Boolean)) break;
  }
}
const out = E.TECHNIQUES.map(t => { const f = found[t.id]; if (!f) throw new Error('missing ' + t.id); const { q, ...rest } = f; return rest; });
fs.writeFileSync('data/examples.json', JSON.stringify(out));
fs.writeFileSync('www/js/data.js', `// Generated by tools/gen-examples.mjs\nexport const BANK = ${fs.readFileSync('data/bank.json', 'utf8')};\nexport const EXAMPLES = ${JSON.stringify(out)};\n`);
for (const e of out) console.log(e.id, 'filled', [...e.grid].filter(c => c !== '0').length, 'elim', e.step.elim.length, '|', e.step.lines.join(' ').slice(0, 150));
